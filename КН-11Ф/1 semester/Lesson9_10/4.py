#Після посадки дерев садівнику потрібно їх пофарбувати.
#У його розпорядженні є фарба трьох кольорів: біла, синя і помаранчева.
#Скількома способами він може пофарбувати N дерев, якщо ніякі два однакові кольори не можуть бути поруч?
n = abs(int(input("Введіть кількість дерев: ")))
print(f"Кількість способів пофарбування дерев: {3 * (pow(2, n-1))}")