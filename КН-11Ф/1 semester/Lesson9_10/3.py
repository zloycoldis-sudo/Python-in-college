#Необхідно сформувати команду, яка буде представляти навчальний заклад у змаганнях з тенісу.
#У секції тенісу займається A дівчат і B хлопців.
#Скільки різних змішаних пар можна вибрати для участі у змаганнях?
boys = abs(int(input("Введіть кількість хлопців: ")))
girls = abs(int(input("Введіть кількість дівчат: ")))
print(f"Кількість різних змішаних пар: {boys * girls}")