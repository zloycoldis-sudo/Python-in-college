#Дано чотиризначне число. Визначте, чи є його десятковий запис симетричним. 
#Якщо число симетричне, виведіть 1, інакше виведіть будь-яке інше ціле число.
number = int(input("Введіть чотиризначне число: "))
n1 = number // 1000
n2 = (number // 100) % 10
n3 = (number // 10) % 10
n4 = number % 10
if n1 == n4 and n2==n3:
    print(1)
else:
    print(0)