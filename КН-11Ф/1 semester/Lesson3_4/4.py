#Книга коштує a гривень b копійок. 
#Визначте, скільки гривень і копійок потрібно заплатити за n книг. 
#Вивести суму до сплати в одному рядку: кількість гривень і копійок відповідно.
grn = int(input("Введіть кількість гривень: "))
cop = int(input("Введіть кількість копійок: "))
n = int(input("Введіть кількість книг: "))
operation = (grn * 100 + cop)*n
print(f"Сума до сплати: {operation // 100} грн. {operation % 100} коп.")