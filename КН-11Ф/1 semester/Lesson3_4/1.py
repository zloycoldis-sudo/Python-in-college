#З початку доби пройшло n хвилин. Який час показує електронний годинник (годин : хвилин)?
#Наприклад, якщо з початку доби пройшло 250 хвилин, то час на годиннику 4:10.
time = int(input("Вкажіть кількість пройдених хвилин з початку доби: "))
time = time % 1440
hour = time // 60
minute = time % 60
print(f"Час на годиннику: {hour}:{minute}")