#На вході програми маємо три натуральних числа a, b і c, записані в одному рядку через пропуск.
#У відповідь потрібно вивести суму заданих чисел, якщо існує трикутник з довжинами сторін a, b, c і повідомлення No у протилежному випадку.
a, b, c = map(int, input("Введіть три натуральні числа через пробіл: ").split())
if a <= 0 or b <= 0 or c <= 0:
    print("No")
elif a + b > c and a + c > b and b + c > a:
    print(f"Сума чисел: {a + b + c}")
else:
    print("No")