#Увести номер дня тижня, вивести його назву словами.
#Наприклад, якщо введено номер 3, то вивести середа.
day = abs(input("Введіть номер дня: "))
if day == 1:
    print('Понеділок')
elif day == 2:
    print('Вівторок')
elif day == 3:
    print('Середа')
elif day == 4:
    print('Четвер')
elif day == 5:
    print('П\'ятниця')
elif day == 6:
    print('Субота')
elif day == 7:
    print('Неділя')
else:
    print('Вкажіть день в діапазоні від 1 до 7')