#На вході програми маємо послідовність цілих чисел, що закінчується числом 0.
#Знайти довжину даної послідовності, не враховуючи останнього нуля.
length = 0
number = int(input(f"Введіть {length+1}-е число: "))
while number != 0:
    length += 1
    number = int(input(f"Введіть {length+1}-е число: "))
print(f"Довжина послідовності: {length}")